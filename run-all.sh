#!/usr/bin/env bash
# 一键执行本轮所有待办：
#   1. 编译校验          （build-check.sh）
#   2. 对本地开发库执行 schema 对齐 DDL（apply-ddl.sh，带自动备份）
#   3. 删除零引用死代码   （delete-dead.sh）
#
# 用法：bash run-all.sh
# 编译失败会立即中止，不会带着坏代码去改数据库。
set -eu
cd "$(dirname "$0")"

echo "############################################"
echo "# 0/4 清理 Lombok 警告（先做，好让编译把改动一起验掉）"
echo "############################################"
bash cleanup-lombok.sh

echo
echo "############################################"
echo "# 1/4 删除零引用死代码（先删，让编译校验的是最终状态）"
echo "############################################"
bash delete-dead.sh

echo
echo "############################################"
echo "# 2/4 编译校验"
echo "############################################"
# build-check.sh 编译失败会返回非零码，set -e 会在这里中止，
# 不会带着坏代码去改数据库。
bash build-check.sh

echo
echo "############################################"
echo "# 3/4 数据库 schema 对齐（本地开发库）"
echo "############################################"
bash apply-ddl.sh

echo
echo "全部完成"
